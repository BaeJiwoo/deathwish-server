"""Bake the original one-second DeathWish walk to its 60 Hz wire pitch samples."""

from argparse import ArgumentParser
from pathlib import Path


SAMPLE_RATE_HZ = 60
HALF_CYCLE = SAMPLE_RATE_HZ // 2
OUTPUT = Path(__file__).resolve().parents[2] / "src/DeathWish.Protocol/AnimationWalkClip.g.cs"

# Eight equally spaced authored keys per channel, in centidegrees.
TORSO = (125, 0, -125, 0, 125, 0, -125, 0)
HEAD = (-75, 0, 75, 0, -75, 0, 75, 0)
UPPER_ARM = (2200, 1450, 0, -1500, -2200, -1450, 0, 1500)
FOREARM = (-1800, -2100, -2450, -2300, -1900, -1650, -1400, -1500)
THIGH = (-2200, -1000, 800, 2000, 2300, 1200, -700, -2300)
SHIN = (500, 800, 900, 1800, 3800, 6300, 4500, 1600)


def sample_channel(keys: tuple[int, ...], tick: int) -> int:
    key, remainder = divmod(tick % SAMPLE_RATE_HZ * len(keys), SAMPLE_RATE_HZ)
    # Exact integer smoothstep makes the bake reproducible across Python versions.
    denominator = SAMPLE_RATE_HZ**3
    ease = remainder**2 * (3 * SAMPLE_RATE_HZ - 2 * remainder)
    first = keys[key]
    second = keys[(key + 1) % len(keys)]
    weighted = first * (denominator - ease) + second * ease
    rounded = (abs(weighted) + denominator // 2) // denominator
    return rounded if weighted >= 0 else -rounded


def bake() -> str:
    channels = (
        (TORSO, 0), (HEAD, 0),
        (UPPER_ARM, 0), (FOREARM, 0), (UPPER_ARM, HALF_CYCLE), (FOREARM, HALF_CYCLE),
        (THIGH, 0), (SHIN, 0), (THIGH, HALF_CYCLE), (SHIN, HALF_CYCLE),
    )
    rows = []
    for tick in range(SAMPLE_RATE_HZ):
        values = (0, *(sample_channel(keys, tick + shift) for keys, shift in channels))
        rows.append("        " + ", ".join(f"{value:5}" for value in values) + ",")
    return "\n".join((
        "// Generated by tools/animation/bake_walk.py.",
        "using System;",
        "",
        "namespace DeathWish.Protocol;",
        "",
        "internal static class AnimationWalkClip",
        "{",
        "    private static readonly short[] PitchCentidegrees =",
        "    {",
        *rows,
        "    };",
        "",
        "    internal static ReadOnlySpan<short> Samples => PitchCentidegrees;",
        "}",
        "",
    ))


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = bake()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "The checked-in walk clip differs from the authored bake.\n")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
