"""Bake ShooterPack's forward walk to the DeathWish rig's 60 Hz local X pitches.

Run python3 tools/animation/bake_walk.py [--check] with Blender on PATH.
The default input is the sibling deathwish-assets/Animations/ShooterPack.zip.
"""

import argparse
import math
from pathlib import Path
import subprocess
import sys
import tempfile
from zipfile import ZipFile


SERVER = Path(__file__).resolve().parents[2]
OUTPUT = SERVER / "src/DeathWish.Protocol/AnimationWalkClip.g.cs"
SOURCE_CLIP = "walk forward.fbx"
SAMPLE_RATE_HZ = 60
DURATION_SECONDS = 1

# In AnimationRig wire order: FBX segment, server parent index, rest direction (+up/-down).
CHANNELS = (
    ("Hips", "Neck", 0, 1),
    ("Head", "HeadTop_End", 1, 1),
    ("LeftArm", "LeftForeArm", 1, -1),
    ("LeftForeArm", "LeftHand", 3, -1),
    ("RightArm", "RightForeArm", 1, -1),
    ("RightForeArm", "RightHand", 5, -1),
    ("LeftUpLeg", "LeftLeg", 0, -1),
    ("LeftLeg", "LeftFoot", 7, -1),
    ("RightUpLeg", "RightLeg", 0, -1),
    ("RightLeg", "RightFoot", 9, -1),
)


def sample_pitches(armature, bones):
    absolute = [0.0]
    pitches = [0]
    for start, end, parent, rest in CHANNELS:
        # Differences discard hip translation. Blender +Z is up and -Y is character forward.
        segment = armature.matrix_world.to_3x3() @ (bones[end].head - bones[start].head)
        angle = math.atan2(-rest * segment.y, rest * segment.z)
        local = math.remainder(angle - absolute[parent], math.tau)
        pitches.append(round(math.degrees(local) * 100))
        absolute.append(angle)
    return pitches


def bake(pack_path):
    import bpy

    with tempfile.TemporaryDirectory() as work, ZipFile(pack_path) as pack:
        source = pack.extract(SOURCE_CLIP, work)
        bpy.ops.import_scene.fbx(filepath=source, use_anim=True)
    armature, = (obj for obj in bpy.context.selected_objects if obj.type == "ARMATURE")
    bones = {bone.name.split(":")[-1]: bone for bone in armature.pose.bones}
    scene = bpy.context.scene
    first, last = armature.animation_data.action.frame_range
    fps = scene.render.fps / scene.render.fps_base
    if not math.isclose((last - first) / fps, DURATION_SECONDS):
        raise ValueError("The forward walk must match AnimationRig's one-second phase.")

    samples = []
    for tick in range(SAMPLE_RATE_HZ * DURATION_SECONDS + 1):
        time = first + tick * fps / SAMPLE_RATE_HZ
        scene.frame_set(math.floor(time), subframe=time % 1)
        samples.append(sample_pitches(armature, bones))

    # The final FBX key repeats the start pose at a different world position.
    last_pose = samples.pop()
    seam = max(abs(a - b) for a, b in zip(samples[0], last_pose))
    if seam > 100:
        raise ValueError(f"Loop endpoint differs by {seam / 100:.2f} degrees.")
    rows = ["        " + ", ".join(f"{pitch:6d}" for pitch in row) + "," for row in samples]
    return "\n".join((
        "// Generated by tools/animation/bake_walk.py from ShooterPack.zip / walk forward.fbx.",
        "using System;",
        "",
        "namespace DeathWish.Protocol;",
        "",
        "internal static class AnimationWalkClip",
        "{",
        "    private static readonly short[] PitchCentidegrees =",
        "    {",
        *rows,
        "    };",
        "",
        "    internal static ReadOnlySpan<short> Samples => PitchCentidegrees;",
        "}",
        "",
    ))


def main():
    # Keep the original Python entry point; Blender supplies the FBX evaluator for the bake.
    if "--" not in sys.argv:
        command = ["blender", "-b", "--factory-startup", "--python-exit-code", "1",
                   "--python", str(Path(__file__).resolve()), "--", *sys.argv[1:]]
        try:
            return subprocess.run(command).returncode
        except FileNotFoundError:
            sys.exit("Blender is required to bake the FBX. Add blender to PATH.")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, default=SERVER.parent / "deathwish-assets")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:])
    result = bake(args.assets / "Animations/ShooterPack.zip")
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "The checked-in walk clip differs from the FBX bake.\n")
    else:
        OUTPUT.write_text(result, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
